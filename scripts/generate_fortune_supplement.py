"""Generate scalable TypeScript seed records from a licensed/public CSV export.

Structural company facts come from the source CSV. Impact500 scores, narratives,
milestones, and news are explicitly modeled demonstration content.
"""
import csv
import json
import re
from pathlib import Path

SOURCE = Path("/tmp/fortune500.csv")
TARGET = Path("data/fortune-supplement.generated.ts")
CURATED = {"microsoft", "salesforce", "patagonia", "cisco", "nike", "walmart", "apple", "target"}

def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")

def q(value):
    return json.dumps(value, ensure_ascii=False)

with SOURCE.open(newline="", encoding="utf-8-sig") as handle:
    rows = list(csv.DictReader(handle))

selected = []
seen = set(CURATED)
for row in rows:
    key = slug(row["Title"])
    if not key or key in seen:
        continue
    seen.add(key)
    selected.append(row)
    if len(selected) == 194:
        break

sectors = sorted({row["Sector"].strip() or "Diversified" for row in selected})
lines = [
    "// Generated by scripts/generate_fortune_supplement.py.",
    "// Structural facts: historical Fortune dataset. CSR analysis: modeled demonstration data.",
    'import type { Company, Industry } from "@/lib/domain/types";',
    "",
    "export const supplementalIndustries: Industry[] = [",
]
for sector in sectors:
    lines.append(f"  {{ slug: {q(slug(sector))}, name: {q(sector)}, description: {q('Comparative corporate-responsibility research across the ' + sector.lower() + ' sector.')}, outlook: {q('Impact500 is monitoring disclosure quality, verified outcomes, workforce practices, ethics, and financial responsibility across this sector.')}, keyIssues: [\"Climate transition\", \"Workforce outcomes\", \"Ethical governance\", \"Community impact\"] }},")
lines.extend(["]", "", "type Seed = [number, string, string, string, string, number, number, string];", "const seeds: Seed[] = ["])
for row in selected:
    seed = [int(row["Rank"]), row["Title"].strip(), (row["Ticker"] or "Private").strip(), row["Sector"].strip() or "Diversified", (row["Hqlocation"] or "United States").strip(), int(float(row["Employees"] or 0)), round(float(row["Revenues"] or 0) / 1000, 1), (row["Website"] or "https://example.com").strip()]
    lines.append("  " + json.dumps(seed, ensure_ascii=False, separators=(",", ":")) + ",")
lines.extend([
    "];", "",
    'const slugify = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");',
    "const gradeFor = (score: number) => score >= 90 ? \"A+\" : score >= 85 ? \"A\" : score >= 80 ? \"B+\" : score >= 75 ? \"B\" : score >= 70 ? \"C+\" : \"C\";",
    "",
    "export const supplementalCompanies: Company[] = seeds.map(([rank, name, ticker, industry, headquarters, employees, revenueBillions, website], index) => {",
    "  const slug = slugify(name);",
    "  const seed = [...slug].reduce((sum, character) => sum + character.charCodeAt(0), rank);",
    "  const pillars = { Environmental: 58 + seed % 35, Philanthropy: 56 + (seed * 3) % 37, Ethics: 57 + (seed * 5) % 36, \"Financial responsibility\": 60 + (seed * 7) % 33 };",
    "  const score = Number((Object.values(pillars).reduce((sum, value) => sum + value, 0) / 4).toFixed(1));",
    "  const historicalScores = Array.from({ length: 6 }, (_, year) => ({ year: 2021 + year, score: Number(Math.max(45, score - 5 + year * .8 + ((seed + year) % 3) * .25).toFixed(1)) }));",
    "  return { slug, name, ticker, industry, industrySlug: slugify(industry), headquarters, location: headquarters, founded: null, employees, revenueBillions, fortuneRank: rank, fortuneRankYear: 2017, website, logo: null, score, grade: gradeFor(score), change: Number((historicalScores[5].score - historicalScores[4].score).toFixed(1)), pillars, historicalScores, summary: `${name} is evaluated within the ${industry.toLowerCase()} sector using modeled Impact500 indicators for environmental performance, financial responsibility, philanthropy, and ethics.`, strengths: [\"Published responsibility disclosures\", \"Established enterprise governance\", `Sector-scale ${industry.toLowerCase()} operations`], weaknesses: [\"Outcome evidence requires continued review\", \"Modeled score pending source-level verification\"], initiatives: [{ title: \"Operational responsibility program\", detail: \"Placeholder initiative record pending company-specific source verification.\" }, { title: \"Community and workforce investment\", detail: \"Placeholder program summary for the expanded research queue.\" }], recentNews: [{ headline: `${name} profile enters expanded Impact500 review`, publishedAt: \"2026-07-01\", summary: \"Placeholder news record pending editorial verification.\" }], researchNotes: [\"This expanded profile uses modeled CSR values and awaits source-level analyst review.\", \"Structural company facts originate from the historical Fortune seed dataset.\"], sources: [{ title: \"Historical Fortune company dataset\", publisher: \"Fortune dataset archive\", year: 2017, url: \"https://github.com/Redislabs-Solution-Architects/redisearch_demo_and_preso/blob/master/fortune500.csv\", accessed: \"2026-07-22\" }, { title: \"Impact500 methodology\", publisher: \"Impact500 Research Desk\", year: 2026, url: \"/methodology\", accessed: \"2026-07-22\" }], relatedCompanies: [slugify(seeds[(index + 1) % seeds.length][1]), slugify(seeds[(index + 2) % seeds.length][1])], lastReviewed: \"2026-07-01\" } satisfies Company;",
    "});", "",
    "export const supplementalDataNotice = {", '  structuralSourceYear: 2017,', '  csrStatus: "modeled" as const,', f"  generatedCompanyCount: {len(selected)},", "};", ""
])
TARGET.write_text("\n".join(lines), encoding="utf-8")
print(f"generated {len(selected)} companies across {len(sectors)} industries")
